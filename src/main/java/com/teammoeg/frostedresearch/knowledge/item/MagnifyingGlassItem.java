package com.teammoeg.frostedresearch.knowledge.item;

import java.util.List;
import javax.annotation.Nullable;

import com.teammoeg.frostedresearch.item.FRBaseItem;
import net.minecraft.ChatFormatting;
import net.minecraft.network.chat.Component;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.TooltipFlag;
import net.minecraft.world.level.Level;

public final class MagnifyingGlassItem extends FRBaseItem {
    public MagnifyingGlassItem(Properties properties) {
        super(properties);
    }

    @Override
    public void appendHoverText(ItemStack stack, @Nullable Level level, List<Component> lines, TooltipFlag flag) {
        lines.add(Component.translatable("tooltip.frostedresearch.magnifying_glass").withStyle(ChatFormatting.GRAY));
    }
}
