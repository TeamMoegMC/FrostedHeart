package com.teammoeg.frostedheart.content.utility;

import java.util.List;

import com.teammoeg.frostedheart.util.Lang;

import net.minecraft.ChatFormatting;
import net.minecraft.network.chat.Component;
import net.minecraft.server.level.ServerPlayer;
import net.minecraft.world.InteractionHand;
import net.minecraft.world.InteractionResult;
import net.minecraft.world.InteractionResultHolder;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.TooltipFlag;
import net.minecraft.world.level.Level;

public class CreativeThermometerItem extends ThermometerItem {

    public CreativeThermometerItem(Properties properties) {
        super(properties);
    }

    @Override
    public void appendHoverText(ItemStack stack, Level level, List<Component> tooltip, TooltipFlag flag) {
        tooltip.add(Lang.translateTooltip("creative_thermometer.usage").withStyle(ChatFormatting.GRAY));
    }

    @Override
    public InteractionResultHolder<ItemStack> use(Level level, Player player, InteractionHand hand) {
        ItemStack stack = player.getItemInHand(hand);
        if (!level.isClientSide && player instanceof ServerPlayer serverPlayer) {
            serverPlayer.sendSystemMessage(Lang.translateMessage(
                    "info.creative_thermometerbody",
                    Float.toString(getRawTemperature(serverPlayer))));
        }
        return new InteractionResultHolder<>(InteractionResult.SUCCESS, stack);
    }
}
